/** Original pixel art expressed as horizontal rectangles, one list per animation frame. */
internal object ClickerAnimalArt {
    internal class ColorRuns(val color: Int, val runs: IntArray)
    internal class Animation(
        private val width: Int,
        private val height: Int,
        private val frames: List<List<ColorRuns>>
    ) {
        /** Share the geometry while choosing the colors once, outside the drawing loop. */
        fun recolored(colors: Map<Int, Int>) = Animation(width, height, frames.map { frame ->
            frame.map { group -> ColorRuns(colors[group.color] ?: group.color, group.runs) }
        })

        fun draw(canvas: Canvas, paint: Paint, frame: Int, targetWidth: Int, targetHeight: Int) {
            if (targetWidth <= 0 || targetHeight <= 0) return
            val saved = canvas.save()
            canvas.scale(targetWidth.toFloat() / width, targetHeight.toFloat() / height)
            for (group in frames[frame]) {
                paint.color = group.color
                val runs = group.runs
                for (i in runs.indices step 3) {
                    val x = runs[i].toFloat()
                    val y = runs[i + 1].toFloat()
                    canvas.drawRect(x, y, x + runs[i + 2], y + 1f, paint)
                }
            }
            canvas.restoreToCount(saved)
        }
    }
