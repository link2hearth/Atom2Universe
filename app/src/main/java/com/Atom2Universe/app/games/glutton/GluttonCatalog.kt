/**
 * Every swallowable thing and its real-world size in metres: objects only, from a sesame seed on the
 * kitchen floor to the great walls of galaxies. Each theme lists its objects in slot order; slot / 24 is
 * the WebP page (assets/glutton/<theme>_<page>.webp, 6 × 4 cells) and slot % 24 the cell. The [Shape] is
 * the code-drawn stand-in used until the page exists. tools/glutton/prompts.py reads this file.
 */
object GluttonCatalog {
    /** STILL waits; WANDER drifts about; CHASE bumps you while you are smaller; PATROL drives along a lane; ORBIT circles a centre. */
    enum class Motion { STILL, WANDER, CHASE, PATROL, ORBIT }
    /**
     * Where the layout puts a thing. FOOD and CLUTTER lie about in little heaps, FURNITURE stands against a
     * wall, CENTRE in the middle of a room, YARD in gardens and parks, STREET along the pavements, VEHICLE
     * on the roads, BUILDING in rows on its lot, TREE in woods and alleys, LANDMARK alone on a square,
     * BODY anywhere in open country, sea or space.
     */
    enum class Role { FOOD, CLUTTER, FURNITURE, CENTRE, YARD, STREET, VEHICLE, BUILDING, TREE, LANDMARK, BODY }
    enum class Shape {
        CRUMB, BERRY, COOKIE, DONUT, SOCK, DUCK, POTPLANT, LAMP, CHAIR, TABLE, SOFA, FRIDGE,
        FLOWERS, BIN, BIKE, WHEELBARROW, BENCH, PARASOL, TREE, PLAYHOUSE, VAN, CARAVAN, SHED, GREENHOUSE,
        CONE, SCOOTER, CAR, BUS, KIOSK, FOUNTAIN, HOUSE, APARTMENT, TOWER, STADIUM, CITYHALL, CLOCKTOWER,
        BALL, BOX, DISC, CAN, VACUUM, MOWER, TRAIN, GNOME, STATUE, TEDDY, BALLOON, HOURGLASS,
        PEAK, BLOB, LAKE, FOREST, CLOUD, PLANET, STAR, NEBULA, CLUSTER, SPIRAL
    }
    /** The eras of the journey, from the start outwards: your house, its suburb, the town, … the whole universe. */
    enum class Theme { ROOM, SUBURB, CITY, COUNTRY, MOUNTAINS, EARTH, PLANETS, STARS, GALAXY, COSMOS }
    const val COLUMNS = 6
    const val ROWS = 4
    const val PAGE = COLUMNS * ROWS

    /**
     * [metres] is the real size; a thing with [spread] > 1 (a lake, a cloud, a galaxy) comes in any size
     * from metres / spread to metres × spread. [rooms] lists the rooms of the house it belongs to:
     * K kitchen, L living room, B bedroom, T bathroom, O office, C children's room.
     */
    class Prop(val index: Int, val id: String, val theme: Theme?, val slot: Int, val metres: Double,
        val shape: Shape, val motion: Motion, val speed: Double, val role: Role, val rooms: String, val spread: Double) {
        val page get() = slot / PAGE
        val cell get() = slot % PAGE
        /** Radius in metres. */
        val radius get() = metres * .5
        val moves get() = motion != STILL
        /** Drawn in code only: the same picture must work at every scale of the world. */
        val bonus get() = theme == null
    }

    private class Builder(val theme: Theme?, val target: ArrayList<Prop>) {
        var slot = 0
        fun p(id: String, metres: Double, shape: Shape, role: Role, motion: Motion = STILL, speed: Double = 0.0,
            rooms: String = "", spread: Double = 1.0) {
            target += Prop(target.size, id, theme, if (theme == null) -1 else slot++, metres, shape, motion, speed, role, rooms, spread)
        }
    }
    private fun ArrayList<Prop>.theme(theme: Theme?, block: Builder.() -> Unit) { Builder(theme, this).block() }

