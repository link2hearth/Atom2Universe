        return pixels(if (!item.equipped) basePiece(item.slot) else if (item.family != Archetype.WARRIOR) DungeonClassSprites.source(item) else when (item.slot) {
            EquipSlot.HELMET -> if (item.isotope) HELMET_ISOTOPE else HELMET
