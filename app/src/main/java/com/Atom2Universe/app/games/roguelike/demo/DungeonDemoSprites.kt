            EquipSlot.BOOTS -> if (item.isotope) BOOTS_ISOTOPE else BOOTS
            EquipSlot.WEAPON -> if (item.isotope) SWORD_ISOTOPE else SWORD
            EquipSlot.OFFHAND -> if (item.isotope) SHIELD_ISOTOPE else SHIELD
            else -> error("Unsupported demo slot: ${item.slot}")
        }, colors)
